def site_page(d: dict) -> str:
    e = html.escape
    videos = "\n".join(
        f'    <tr><td><a href="{e(v["page"])}">{e(v["title"])}</a></td><td>{mmss(v.get("seconds"))}</td>'
        f'<td>{e(v.get("summary", ""))} <span class="small">(checked against {e(str(v.get("version", "?")))})</span></td></tr>'
        for v in d.get("videos", []))
    movies = "\n".join(
        f'    <tr><td><span class="avatar" aria-hidden="true">{GLYPHS.get(m["agent"], "")}</span>'
        f'<a href="murmurent_agent_{e(m["agent"])}.html">{e(m.get("title", m["agent"]))}</a></td>'
        f'<td>{mmss(m.get("seconds"))}</td><td>{e(m.get("tagline", ""))}</td></tr>'
        for m in d["movies_in_order"])
    news = "\n".join(
        f'    <tr><td class="date">{e(str(n["date"]))}</td><td><strong>{e(n["title"])}</strong>. {e(n.get("summary", ""))}'
        + (f' <a href="{e(n["link"])}">More</a>.' if n.get("link") else "") + "</td></tr>"
        for n in sorted(d.get("news", []), key=lambda n: str(n.get("date")), reverse=True))
    return PAGE.format(videos=videos, movies=movies, news=news, repo=REPO)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--site", default="~/repos/hallettmiket.github.io")
    ap.add_argument("--check", action="store_true", help="report stale README sections, write nothing")
    args = ap.parse_args()
    d = load()
    section = readme_section(d)
    stale = 0
    for readme in READMES:
        if not readme.exists():
            continue
        new = splice(readme.read_text(), section)
        if new != readme.read_text():
            stale += 1
            if args.check:
                print(f"out of date: {readme.relative_to(ROOT)}")
            else:
                readme.write_text(new)
                print(f"wrote the Videos and news section of {readme.relative_to(ROOT)}")
    if args.check:
        sys.exit(1 if stale else 0)
    dest = Path(args.site).expanduser() / "assets" / "videos"
    if dest.is_dir():
        (dest / "index.html").write_text(site_page(d))
        print(f"wrote {dest / 'index.html'}: {len(d.get('videos', []))} videos, {len(d['movies_in_order'])} agent movies, "
              f"{len(d.get('news', []))} news items")
    else:
        print(f"site folder not found, page not written: {dest}", file=sys.stderr)


if __name__ == "__main__":
    main()
