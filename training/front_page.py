#!/usr/bin/env python3
"""
Purpose: Write the two public faces of murmurent's videos and news from one
         source (issue #289): the "Videos and news" section of README.md and
         release/README_public.md (between generated markers), and the page at
         <site>/assets/videos/index.html that plays every video and lists the
         news. Everything comes from training/index.yaml, so the two surfaces
         cannot drift apart.
Author: Mike Hallett (with Claude Code)
Date: 2026-11-07
Input: training/index.yaml (videos, movies, news).
Output: the README sections rewritten in place; <site>/assets/videos/index.html.
Usage: python3 training/front_page.py [--site ~/repos/hallettmiket.github.io] [--check]
       --check: exit 1 if a README section is out of date, write nothing.
"""

from __future__ import annotations

import argparse
import html
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from lib.glyphs import GLYPHS  # noqa: E402  (each agent's avatar, as its movie draws it)

ROOT = Path(__file__).resolve().parents[1]
INDEX = ROOT / "training" / "index.yaml"
READMES = [ROOT / "README.md", ROOT / "release" / "README_public.md"]
START = "<!-- videos-and-news: generated by training/front_page.py from training/index.yaml; do not edit -->"
END = "<!-- /videos-and-news -->"
SITE = "https://mikehallett.science/assets/videos/"
REPO = "https://github.com/hallettmiket/murmurent/blob/main/"
AGENT_ORDER = ["oracle", "bookworm", "adversary", "artist", "scribe", "teacher", "lab_oracle", "blacksmith",
               "conscience", "lawyer", "millwright", "centre_millwright", "judge", "registrar", "security_guard",
               "clerk", "docent"]


def load() -> dict:
    d = yaml.safe_load(INDEX.read_text()) or {}
    movies = {m["agent"]: m for m in d.get("movies", [])}
    d["movies_in_order"] = [movies[a] for a in AGENT_ORDER if a in movies] + \
        [m for a, m in movies.items() if a not in AGENT_ORDER]
    return d


def mmss(seconds) -> str:
    s = int(seconds or 0)
    return f"{s // 60}:{s % 60:02d}"


# --------------------------------------------------------------------------- #
# README section (Markdown)
# --------------------------------------------------------------------------- #


def readme_section(d: dict) -> str:
    out = [START, "", "## Videos and news", "",
           f"Every video, in one place: <{SITE}>. Each one says which release it was checked against;",
           "when a video and the written documentation disagree, the documentation is right.", ""]
    out += ["| Video | Length | Covers |", "|---|---|---|"]
    for v in d.get("videos", []):
        out.append(f"| [{v['title']}]({v['page']}) | {mmss(v.get('seconds'))} | {v.get('summary', '')} "
                   f"(checked against {v.get('version', '?')}) |")
    if d["movies_in_order"]:
        out += ["", "One two-minute movie per agent: what it does, what it will not do, one real run, and how to",
                "use it through Claude Code.", "", "| Agent | Movie | Length |", "|---|---|---|"]
        for m in d["movies_in_order"]:
            out.append(f"| [`{m['agent']}`]({REPO}agents/{m['agent']}.md) "
                       f"| [{m.get('title', m['agent'])}]({SITE}murmurent_agent_{m['agent']}.html) | {mmss(m.get('seconds'))} |")
    news = sorted(d.get("news", []), key=lambda n: str(n.get("date")), reverse=True)
    if news:
        out += ["", "**News**, newest first (releases and new capabilities; the full record is the",
                f"[changelog]({REPO}CHANGELOG.md)):", ""]
        for n in news:
            link = f" [More]({n['link']})." if n.get("link") else ""
            out.append(f"- **{n['date']}**: {n['title']}. {n.get('summary', '')}{link}")
    out += ["", END]
    return "\n".join(out) + "\n"


def splice(text: str, section: str) -> str:
    if START in text and END in text:
        a = text.index(START)
        b = text.index(END) + len(END) + 1
        return text[:a] + section + text[b:]
    # first time: before "## Help" in the public README, else at the end
    anchor = "\n## Help\n"
    if anchor in text:
        i = text.index(anchor)
        return text[:i] + "\n" + section + text[i:]
    return text.rstrip("\n") + "\n\n" + section


